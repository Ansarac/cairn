"""Opening a database an older build wrote.

A hub in a container was upgraded from the build tagged here as *before subjects*
to the one after `retracted_at` landed, and went into a restart loop:
`sqlite3.OperationalError: no such column: supersedes`. It was recovered by wiping
the volume, which for a store that is the only copy of the sediment on it means
the upgrade destroyed the product. Nothing in the suite went red, before or after.

**The reason nothing went red is the reason this file exists.** The upgrade test
that already existed built its "old" database by calling `SqliteStore(path)` and
then dropping one table — so `notes` was left entirely modern and the index that
crashes could still be built. A fixture generated by the code under test can only
ever represent the schema the code under test writes, which is precisely the one
thing an upgrade test must not assume. That test is still in `test_subjects.py`
and its docstring now says which half it covers.

So the schemas below are **literal SQL, copied verbatim from `git show
<sha>:src/cairn/store.py`**, and they are checked in as a record of what those
builds actually wrote rather than as a description of what they meant to. They do
not get updated when `store.py` changes; a new one gets added underneath. The
oldest was validated against the real pre-upgrade database off the container hub,
which reproduces the same failure and is not committed — it is a production store
full of real hostnames, and its schema was what was wanted, not its bytes.
"""

